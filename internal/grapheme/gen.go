//go:build ignore

// gen downloads the Unicode Character Database files that define extended grapheme clusters and
// writes tables.go and testdata/GraphemeBreakTest.txt. Run it through go generate when the Unicode
// version changes:
//
//	go run gen.go -version 17.0.0
//
// It reads three properties: Grapheme_Cluster_Break (GraphemeBreakProperty.txt),
// Extended_Pictographic (emoji-data.txt), and Indic_Conjunct_Break (DerivedCoreProperties.txt).
package main

import (
	"bufio"
	"bytes"
	"flag"
	"fmt"
	"go/format"
	"io"
	"log"
	"net/http"
	"os"
	"strconv"
	"strings"
)

// The property values, as tables.go and grapheme.go number them.
var breaks = map[string]uint8{
	"CR": 1, "LF": 2, "Control": 3, "Extend": 4, "ZWJ": 5, "Regional_Indicator": 6, "Prepend": 7,
	"SpacingMark": 8, "L": 9, "V": 10, "T": 11, "LV": 12, "LVT": 13,
}

var conjuncts = map[string]uint8{"Consonant": 1, "Linker": 2, "Extend": 3}

const (
	pictographic  = 1 << 4
	conjunctShift = 5
)

func main() {
	version := flag.String("version", "", "the Unicode version, such as 17.0.0")
	flag.Parse()
	if *version == "" {
		log.Fatal("gen: -version is required")
	}
	base := "https://www.unicode.org/Public/" + *version + "/ucd/"

	props := make([]uint8, 0x110000)
	parse(fetch(base+"auxiliary/GraphemeBreakProperty.txt"), func(lo, hi rune, f []string) {
		v, ok := breaks[f[0]]
		if !ok {
			log.Fatalf("gen: unknown Grapheme_Cluster_Break value %q", f[0])
		}
		for r := lo; r <= hi; r++ {
			props[r] |= v
		}
	})
	parse(fetch(base+"emoji/emoji-data.txt"), func(lo, hi rune, f []string) {
		if f[0] != "Extended_Pictographic" {
			return
		}
		for r := lo; r <= hi; r++ {
			props[r] |= pictographic
		}
	})
	incb := 0
	parse(fetch(base+"DerivedCoreProperties.txt"), func(lo, hi rune, f []string) {
		if f[0] != "InCB" {
			return
		}
		v, ok := conjuncts[f[1]]
		if !ok {
			log.Fatalf("gen: unknown Indic_Conjunct_Break value %q", f[1])
		}
		incb++
		for r := lo; r <= hi; r++ {
			props[r] |= v << conjunctShift
		}
	})
	if incb == 0 {
		log.Fatal("gen: DerivedCoreProperties.txt has no InCB lines")
	}

	var b bytes.Buffer
	fmt.Fprintf(&b, `// Code generated by gen.go from the Unicode Character Database %s. DO NOT EDIT.
// The data is © Unicode, Inc., under the license at https://www.unicode.org/license.txt.

package grapheme

// Version is the Unicode version the tables follow.
const Version = %q

// ranges lists, in order, every run of code points whose properties are not all zero.
var ranges = [...]span{
`, *version, *version)
	n := 0
	for lo := 0; lo < len(props); {
		hi := lo
		for hi+1 < len(props) && props[hi+1] == props[lo] {
			hi++
		}
		if props[lo] != 0 {
			fmt.Fprintf(&b, "\t{0x%04X, 0x%04X, 0x%02X},\n", lo, hi, props[lo])
			n++
		}
		lo = hi + 1
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("tables.go", src, 0o644); err != nil {
		log.Fatal(err)
	}
	if err := os.WriteFile("testdata/GraphemeBreakTest.txt", fetch(base+"auxiliary/GraphemeBreakTest.txt"), 0o644); err != nil {
		log.Fatal(err)
	}
	log.Printf("gen: %d ranges for Unicode %s", n, *version)
}

func fetch(url string) []byte {
	resp, err := http.Get(url)
	if err != nil {
		log.Fatal(err)
	}
	defer resp.Body.Close()
	if resp.StatusCode != http.StatusOK {
		log.Fatalf("gen: %s: %s", url, resp.Status)
	}
	data, err := io.ReadAll(resp.Body)
	if err != nil {
		log.Fatal(err)
	}
	return data
}

// parse calls f for each data line, "lo..hi ; field ; field # comment", with the fields trimmed.
func parse(data []byte, f func(lo, hi rune, fields []string)) {
	sc := bufio.NewScanner(bytes.NewReader(data))
	for sc.Scan() {
		line, _, _ := strings.Cut(sc.Text(), "#")
		if strings.TrimSpace(line) == "" {
			continue
		}
		fields := strings.Split(line, ";")
		for i := range fields {
			fields[i] = strings.TrimSpace(fields[i])
		}
		first, last, ok := strings.Cut(fields[0], "..")
		if !ok {
			last = first
		}
		lo, err1 := strconv.ParseUint(first, 16, 32)
		hi, err2 := strconv.ParseUint(last, 16, 32)
		if err1 != nil || err2 != nil || lo > hi || hi > 0x10FFFF {
			log.Fatalf("gen: bad range in %q", sc.Text())
		}
		f(rune(lo), rune(hi), fields[1:])
	}
	if err := sc.Err(); err != nil {
		log.Fatal(err)
	}
}
