// Command gen writes zones_gen.go, the zone table of package temporal, from two published
// files: tzdata.zi, the compact form of the IANA time zone database that systems ship under
// zoneinfo (its Z lines are the zones and its L lines the links to them), and CLDR's
// windowsZones.xml, which maps Windows zone names to IANA names. Go's time package has no list
// of zone names and no link table, so the table is what makes a lookup case-insensitive on
// every platform, Asia/Calcutta equal to Asia/Kolkata, and a Windows machine's local zone known.
//
//	go run ./internal/temporal/gen -tzdata /usr/share/zoneinfo/tzdata.zi -windows windowsZones.xml
package main

import (
	"bufio"
	"bytes"
	"encoding/xml"
	"flag"
	"fmt"
	"go/format"
	"log"
	"os"
	"sort"
	"strings"
)

func main() {
	tzdata := flag.String("tzdata", "/usr/share/zoneinfo/tzdata.zi", "the tzdata.zi file")
	windows := flag.String("windows", "", "CLDR's windowsZones.xml")
	out := flag.String("o", "zones_gen.go", "the file to write")
	flag.Parse()
	if *windows == "" {
		log.Fatal("gen: -windows is required")
	}
	if err := generate(*tzdata, *windows, *out); err != nil {
		log.Fatalf("gen: %v", err)
	}
}

// generate writes the table for the two source files to out.
func generate(tzdata, windows, out string) error {
	version, zones, links, err := readTzdata(tzdata)
	if err != nil {
		return err
	}
	winZones, err := readWindows(windows)
	if err != nil {
		return err
	}
	var b bytes.Buffer
	fmt.Fprintf(&b, "// Code generated by internal/temporal/gen from tzdata %s; DO NOT EDIT.\n\n", version)
	b.WriteString("package temporal\n\n")
	fmt.Fprintf(&b, "// tzdataVersion is the version of the IANA database the table was made from.\nconst tzdataVersion = %q\n\n", version)
	b.WriteString("// zoneNames maps every zone name, in lower case, to its spelling in the database.\nvar zoneNames = map[string]string{\n")
	names := append(append([]string{}, zones...), keys(links)...)
	sort.Strings(names)
	for _, n := range names {
		fmt.Fprintf(&b, "\t%q: %q,\n", strings.ToLower(n), n)
	}
	b.WriteString("}\n\n")
	b.WriteString("// zoneLinks maps a link name to the zone it names.\nvar zoneLinks = map[string]string{\n")
	for _, n := range keys(links) {
		fmt.Fprintf(&b, "\t%q: %q,\n", n, links[n])
	}
	b.WriteString("}\n\n")
	b.WriteString("// windowsZones maps a Windows zone name to the IANA zone CLDR gives it.\nvar windowsZones = map[string]string{\n")
	for _, n := range keys(winZones) {
		fmt.Fprintf(&b, "\t%q: %q,\n", n, winZones[n])
	}
	b.WriteString("}\n")
	src, err := format.Source(b.Bytes())
	if err != nil {
		return err
	}
	if err := os.WriteFile(out, src, 0o644); err != nil {
		return err
	}
	fmt.Printf("%s: tzdata %s, %d zones, %d links, %d Windows names\n", out, version, len(zones), len(links), len(winZones))
	return nil
}

func keys(m map[string]string) []string {
	out := make([]string, 0, len(m))
	for k := range m {
		out = append(out, k)
	}
	sort.Strings(out)
	return out
}

// readTzdata returns the version, the zones and the links of a tzdata.zi file. A link line
// reads "L target name"; the version is in a comment on the first line.
func readTzdata(path string) (version string, zones []string, links map[string]string, err error) {
	f, err := os.Open(path)
	if err != nil {
		return "", nil, nil, err
	}
	defer f.Close()
	links = map[string]string{}
	sc := bufio.NewScanner(f)
	for sc.Scan() {
		line := sc.Text()
		if strings.HasPrefix(line, "# version ") {
			version = strings.TrimPrefix(line, "# version ")
			continue
		}
		fields := strings.Fields(line)
		if len(fields) < 2 {
			continue
		}
		switch fields[0] {
		case "Z":
			zones = append(zones, fields[1])
		case "L":
			if len(fields) >= 3 {
				links[fields[2]] = fields[1]
			}
		}
	}
	if err := sc.Err(); err != nil {
		return "", nil, nil, err
	}
	if version == "" || len(zones) == 0 {
		return "", nil, nil, fmt.Errorf("%s does not look like tzdata.zi", path)
	}
	// A link to a link resolves to the zone at the end.
	for name, target := range links {
		for {
			next, ok := links[target]
			if !ok {
				break
			}
			target = next
		}
		links[name] = target
	}
	return version, zones, links, nil
}

// readWindows returns the territory-001 mapping of windowsZones.xml: one IANA zone per
// Windows name.
func readWindows(path string) (map[string]string, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return nil, err
	}
	var doc struct {
		Zones []struct {
			Other     string `xml:"other,attr"`
			Territory string `xml:"territory,attr"`
			Type      string `xml:"type,attr"`
		} `xml:"windowsZones>mapTimezones>mapZone"`
	}
	if err := xml.Unmarshal(data, &doc); err != nil {
		return nil, fmt.Errorf("%s: %v", path, err)
	}
	out := map[string]string{}
	for _, z := range doc.Zones {
		if z.Territory == "001" {
			out[z.Other] = strings.Fields(z.Type)[0]
		}
	}
	if len(out) == 0 {
		return nil, fmt.Errorf("%s has no territory 001 entries", path)
	}
	return out, nil
}
